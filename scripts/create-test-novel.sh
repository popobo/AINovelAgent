#!/bin/bash

# 创建测试用的小说文件

TEST_FILE="test_novel.txt"

cat > "$TEST_FILE" << 'EOF'
第一章 开始

在一个遥远的王国，年轻的冒险者张三踏上了他的冒险之旅。他带着一把祖传的宝剑，心中充满了对未知世界的好奇。

"我一定要成为最伟大的冒险者！"张三握紧拳头，坚定地说道。

他离开了家乡的小村庄，朝着王国的首都进发。沿途风景如画，但也隐藏着未知的危险。

第二章 遇见

走了三天三夜，张三来到了一个繁华的小镇。在小镇的酒馆里，他遇见了李四——一个经验丰富的老冒险者。

"年轻人，你看起来很勇敢。"李四拍了拍张三的肩膀，"要不要一起冒险？"

张三欣然同意。两人结伴而行，李四向张三传授了许多冒险的技巧和知识。

"记住，真正的冒险者不仅要勇敢，还要有智慧。"李四说道。

第三章 挑战

他们来到了著名的"迷雾森林"。据说这里充满了魔法生物和古老的宝藏。

"我们要小心，"李四提醒道，"这里的迷雾会让人迷失方向。"

果然，进入森林后，他们很快就被浓雾包围了。更糟糕的是，他们听到了奇怪的声音——像是野兽的低吼。

"准备战斗！"李四抽出武器。

张三也握紧了自己的宝剑，心中既紧张又兴奋。这是他第一次真正的冒险挑战。

第四章 战斗

突然，一只巨大的魔狼从迷雾中冲了出来。它有三只眼睛，散发着绿色的光芒。

"小心！"李四大喊道。

魔狼扑向张三，张三敏捷地躲开了。他挥剑反击，但魔狼的皮肤异常坚硬，普通攻击根本无法造成伤害。

"它的弱点是第三只眼睛！"李四发现了关键。

张三抓住机会，一剑刺中了魔狼的第三只眼睛。魔狼发出一声惨叫，倒在了地上，化作一团烟雾消失了。

"干得好，年轻人！"李四赞赏地说道。

第五章 宝藏

魔狼消失的地方出现了一个古老的宝箱。张三小心翼翼地打开它，里面是一枚闪闪发光的徽章。

"这是'勇敢者徽章'，"李四认出了这个宝物，"只有真正勇敢的人才能得到它。"

张三拿起徽章，感到一股温暖的力量涌入体内。他知道，这只是他冒险旅程的开始。

"还有很多挑战在等着我们。"张三看着远方，眼中闪烁着坚定的光芒。

李四点点头："是的，但只要有勇气和智慧，我们就能克服一切困难。"

两人继续前行，踏上了新的冒险之路。
EOF

echo "✅ 测试小说文件已创建: $TEST_FILE"
echo "   文件大小: $(wc -c < "$TEST_FILE") 字节"
echo "   章节数: $(grep -c "^第.*章" "$TEST_FILE")"

